// Run: npx tsx lib/link-label.test.ts
import { labelAnchor } from "./link-label";

function assert(cond: boolean, msg: string) {
    if (!cond) throw new Error("FAIL: " + msg);
    console.log("✓ " + msg);
}
const at = (pts: { x: number; y: number }[], b = 34) => {
    const p = labelAnchor(pts, b);
    return `${Math.round(p.x)},${Math.round(p.y)}`;
};

// 1. เส้นตรงยาว → ถอยจากหัวลูกศรตามระยะที่กำหนด
assert(at([{ x: 0, y: 0 }, { x: 100, y: 0 }]) === "66,0", "เส้นนอน ถอย 34 จากปลาย");

// 2. ถอยจากปลาย ไม่ใช่จากต้น — ยืดเส้นแล้วป้ายต้องขยับตามปลายไป
assert(at([{ x: 0, y: 0 }, { x: 200, y: 0 }]) === "166,0", "ยืดเส้น ป้ายเกาะปลายเหมือนเดิม");

// 3. ข้ามช่วง: ช่วงท้ายสั้นกว่า backoff ต้องเดินต่อเข้าไปช่วงก่อนหน้า
assert(at([{ x: 0, y: 0 }, { x: 0, y: 100 }, { x: 20, y: 100 }]) === "0,86", "ช่วงท้ายสั้น เดินต่อเข้าช่วงก่อน");

// 4. เส้นสั้นกว่า backoff ทั้งเส้น → ไปสุดที่จุดเริ่ม ไม่หลุดออกนอกเส้น
assert(at([{ x: 0, y: 0 }, { x: 10, y: 0 }]) === "0,0", "เส้นสั้นมาก → จุดเริ่ม");

// 5. ความนิ่ง: ขยับรูปทรงนิดเดียว ป้ายต้องขยับนิดเดียว ไม่กระโดด
//    (เคสที่ทำให้เกิดบั๊ค — ของเดิมใช้ "ช่วงยาวสุด" พอสองช่วงยาวเท่ากันแล้วสลับกันชนะ ป้ายเด้งข้ามเส้น)
const a = labelAnchor([{ x: 0, y: 0 }, { x: 0, y: 100 }, { x: 100, y: 100 }]);
const b = labelAnchor([{ x: 0, y: 0 }, { x: 0, y: 101 }, { x: 100, y: 101 }]);
assert(Math.abs(a.x - b.x) + Math.abs(a.y - b.y) <= 2, "ขยับ 1px ป้ายขยับไม่เกิน 2px");

// 6. ช่วงยาวเท่ากันเป๊ะ ต้องไม่ทำให้ผลลัพธ์ขึ้นกับลำดับการเปรียบเทียบ
assert(at([{ x: 0, y: 0 }, { x: 50, y: 0 }, { x: 50, y: 50 }]) === "50,16", "สองช่วงยาวเท่ากัน ผลนิ่ง");

// 7. รับ input ว่างโดยไม่ระเบิด
assert(at([]) === "0,0", "ไม่มีจุดเลย → ไม่ระเบิด");

console.log("\nALL PASS ✓");
